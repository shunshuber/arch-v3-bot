def get_random_text(reason_key: str = "") -> str:
    """BR-style single random pick: category pool mixed with the general one."""
    texts = CATEGORY_TEXTS.get(reason_key, OTHER) + GENERAL_TEXTS
    return random.choice(texts)


def get_mixed_texts(reason_key: str = "", count: int = 5) -> list[str]:
    """BR get_mixed_texts analog: category + general, unique sample."""
    texts = CATEGORY_TEXTS.get(reason_key, OTHER) + GENERAL_TEXTS
    return random.sample(texts, min(count, len(texts)))
